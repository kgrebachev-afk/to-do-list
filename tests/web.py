# Version installable : manifeste, service worker, hors ligne, mise à jour, raccourcis, CSP
import sys as _sys, pathlib as _pl; _sys.path.insert(0, str(_pl.Path(__file__).resolve().parent)); from paths import ROOT, TMP, SHOTS, BUILD, test_build
import pathlib, subprocess, sys, time, json, shutil, re
from playwright.sync_api import sync_playwright
ROOT=ROOT
SCR=(TMP/'webtest')
OUT=SHOTS
res=[]; errs=[]; csp=[]
def check(n,c,i=''): res.append(bool(c)); print(('PASS ' if c else 'FAIL ')+n+('' if c else f' — {i}'))
# copie servie sous un sous-chemin, comme GitHub Pages (/to-do-list/)
shutil.rmtree(SCR, ignore_errors=True); (SCR/'site').mkdir(parents=True)
shutil.copytree(test_build('build-web', PAGES_URL='http://127.0.0.1:8780/to-do-list/')/'web', SCR/'site/to-do-list')
srv=subprocess.Popen([sys.executable,'-m','http.server','8780','--bind','127.0.0.1','-d',str(SCR/'site')],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL); time.sleep(0.8)
BASE='http://127.0.0.1:8780/to-do-list/'
try:
  with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(locale='fr-FR', timezone_id='Europe/Paris', viewport={'width':1366,'height':820})
    pg=ctx.new_page()
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.on('console', lambda m: (csp.append(m.text) if 'Content Security Policy' in m.text else None, errs.append(m.text) if m.type=='error' else None))
    pg.goto(BASE); pg.wait_for_timeout(800)
    m = json.loads(pg.evaluate("fetch('manifest.webmanifest').then(r=>r.text()).catch(e=>'ERR')") if False else (SCR/'site/to-do-list/manifest.webmanifest').read_text())
    check('manifeste : nom, affichage, icônes 192/512 + masquable', m['name']=='To do list' and m['display']=='standalone' and {i['sizes'] for i in m['icons']}>={'192x192','512x512'} and any(i['purpose']=='maskable' for i in m['icons']))
    mf = pg.evaluate("document.querySelector('link[rel=manifest]').href")
    check('lien vers le manifeste', mf.endswith('/to-do-list/manifest.webmanifest'), mf)
    # le navigateur sait-il lire le manifeste ? (CDP : erreurs d'installabilité)
    cdp = ctx.new_cdp_session(pg)
    am = cdp.send('Page.getAppManifest')
    check('Chrome lit le manifeste sans erreur', not am.get('errors'), am.get('errors'))
    inst = cdp.send('Page.getInstallabilityErrors')
    check('Chrome considère l\'app installable', not inst.get('installabilityErrors'), inst)
    sw = pg.evaluate("navigator.serviceWorker.ready.then(r=>!!r.active)")
    check('service worker actif', sw)
    pg.reload(); pg.wait_for_timeout(500)
    check('page contrôlée par le service worker', pg.evaluate("!!navigator.serviceWorker.controller"))
    pg.fill('#qaInput','Tâche web'); pg.press('#qaInput','Enter')
    check('stockage persistant demandé', pg.evaluate("navigator.storage.persisted().then(x=>typeof x==='boolean')"))
    # --- hors ligne : le serveur s'arrête (proxy qui bloque, réseau coupé)
    srv.terminate(); srv.wait(); ctx.set_offline(True)
    pg.reload(); pg.wait_for_timeout(500)
    check('hors ligne : l\'app s\'ouvre quand même', pg.locator('h1').inner_text()=='To do list')
    check('hors ligne : les tâches sont là', 'Tâche web' in pg.locator('#list').inner_text())
    pg2 = ctx.new_page(); pg2.goto(BASE + '?nouvelle'); pg2.wait_for_timeout(500)
    check('raccourci « Nouvelle tâche » : champ de saisie actif', pg2.evaluate("document.activeElement.id")=='qaInput', pg2.evaluate("document.activeElement.id"))
    check('raccourci : adresse nettoyée', pg2.url.endswith('/to-do-list/'), pg2.url)
    pg2.close()
    ctx.set_offline(False)
    # --- mise à jour : nouvelle version publiée pendant l'utilisation (application ouverte depuis un moment)
    end = time.time() + 20
    while pg.evaluate("performance.now()") < 16000 and time.time() < end: pg.wait_for_timeout(500)
    srv=subprocess.Popen([sys.executable,'-m','http.server','8780','--bind','127.0.0.1','-d',str(SCR/'site')],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL); time.sleep(0.8)
    idx=SCR/'site/to-do-list/index.html'; idx.write_text(idx.read_text().replace('<h1>To do list</h1>','<h1>To do list</h1><!--v2-->'))
    swf=SCR/'site/to-do-list/sw.js'; swf.write_text(re.sub(r"\+[0-9a-f]{10}'", "+nouvelle00'", swf.read_text()))
    pg.evaluate("navigator.serviceWorker.getRegistration().then(r=>r.update())"); pg.wait_for_timeout(1500)
    toasts = pg.locator('.toast').all_inner_texts()
    check('mise à jour détectée et proposée', any('nouvelle version' in t for t in toasts), toasts)
    pg.locator('.toast button', has_text='Mettre à jour').click(); pg.wait_for_timeout(1500)
    check('après « Mettre à jour » : nouvelle version chargée, tâches conservées', '<!--v2-->' in pg.content() and 'Tâche web' in pg.locator('#list').inner_text())
    # --- réglages : section Application
    pg.click('#btnSettings')
    check('réglages : section Application visible', pg.locator('#setAppSec').is_visible() and 'onglet' in pg.locator('#setAppText').inner_text())
    pg.screenshot(path=str(OUT/'60-web-settings.png'))
    pg.keyboard.press('Escape')
    # --- fenêtre installée (simulée) : pas de carte d'installation
    pg.evaluate("window.__odj.pwa.promptEvent={prompt:async()=>{},userChoice:Promise.resolve({outcome:'accepted'})}; window.__odj.pwa.render()")
    check('dans un onglet : carte « Installer » proposée', pg.locator('#installCard').is_visible())
    check('… et la carte de sauvegarde attend l\'installation', not pg.locator('#setupCard').is_visible())
    pg.screenshot(path=str(OUT/'61-install-card.png'))
    pg.locator('[data-install="go"]').click(); pg.wait_for_timeout(200)
    check('après installation : carte d\'installation masquée, carte sauvegarde affichée', not pg.locator('#installCard').is_visible() and pg.locator('#setupCard').is_visible())
    check('aucune violation CSP', not csp, csp)
    check('aucune requête réseau sortante possible depuis la page', pg.evaluate("fetch('https://example.com').then(()=>'ok').catch(()=>'bloqué')")=='bloqué')
    b.close()
finally:
    srv.terminate()
print('ERREURS:', [e for e in errs if 'example.com' not in e and 'Content Security Policy' not in e] or 'aucune'); print(f'{sum(res)}/{len(res)} OK')
